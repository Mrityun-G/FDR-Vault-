// Generates supabase/seed.sql from the app's demo dataset (data.js) so both modes start from identical records.
// Usage: node supabase/scripts/generate-seed.mjs
import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..', '..');
const ctx = {};
vm.runInNewContext(fs.readFileSync(path.join(root, 'data.js'), 'utf8') + '\n;Object.assign(this, { USERS, INSTITUTIONS, APPS, FDRS, NOTIFS });', ctx);
const { INSTITUTIONS, APPS, FDRS, NOTIFS } = ctx;

// Stable UUIDs derived from the demo ids.
const uid = key => {
  const h = crypto.createHash('sha1').update('aicte-irvp:' + key).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = v => v === null || v === undefined ? 'null' : `'${String(v).replace(/'/g, "''")}'`;
const j = v => v === null || v === undefined ? 'null' : `${q(JSON.stringify(v))}::jsonb`;
const out = [
  '-- Generated by supabase/scripts/generate-seed.mjs from data.js. Demo records only — do not load into production.',
  '-- After creating auth users, link them, e.g.:',
  "--   select public.admin_link_user('principal@dits-delhi.edu.in', '1-10928371');",
  'begin;',
];

for (const i of INSTITUTIONS) {
  out.push(`insert into public.institutions(id, pid, name, short_name, city, district, state, region, type, address, website, sanctioned_intake, total_students, required_fdr_lakhs)
values (${q(uid(i.id))}, ${q(i.pid)}, ${q(i.name)}, ${q(i.short)}, ${q(i.city)}, ${q(i.district)}, ${q(i.state)}, ${q(i.region)}, ${q(i.type)}, ${q(i.address)}, ${q(i.website)}, ${i.sanctionedIntake}, ${i.totalStudents}, ${i.requiredFdrLakhs}) on conflict (pid) do nothing;`);
}

for (const f of FDRS) {
  out.push(`insert into public.fdrs(id, institution_id, fdr_number, application_number, amount, bank_name, branch_name, ifsc_code, issue_date, maturity_date, tenure_years, joint_lien_holder, is_lien_confirmed, lien_endorsement_token, lien_endorsed_at, renewal_status, demo)
values (${q(uid(f.id))}, ${q(uid(f.institutionId))}, ${q(f.fdrNumber)}, ${q(f.applicationNumber)}, ${f.amountLakhs * 100000}, ${q(f.bankName)}, ${q(f.branchName)}, ${q(f.ifscCode)}, ${q(f.issueDate)}, ${q(f.maturityDate)}, ${f.tenureYears}, ${q(f.jointLienHolder)}, ${f.isLienConfirmed}, ${q(f.lienEndorsementToken)}, ${q(f.lienEndorsedAt)}, ${q(f.renewalStatus || 'NOT_APPLICABLE')}, ${!!f.demo}) on conflict (fdr_number) do nothing;`);
}

for (const a of APPS) {
  const fdr = FDRS.find(f => f.fdrNumber === a.fdrNumber);
  out.push(`insert into public.applications(id, application_number, institution_id, type, status, academic_year, programme, intake_details, fdr_id, fdr_number, current_version, rule_version, submitted_at, last_updated_at, declaration)
values (${q(uid(a.id))}, ${q(a.applicationNumber)}, ${q(uid(a.institutionId))}, ${q(a.type)}, ${q(a.status)}, ${q(a.academicYear)}, ${j(a.programme || {})}, ${j({ ...a.intakeDetails })}, ${fdr ? q(uid(fdr.id)) : 'null'}, ${q(a.fdrNumber)}, ${a.currentVersion}, 'v2026.1', ${q(a.submittedAt)}, ${q(a.lastUpdatedAt)}, true) on conflict (application_number) do nothing;`);
  out.push(`insert into public.status_history(application_id, institution_id, from_status, to_status, actor_role, note, at) values (${q(uid(a.id))}, ${q(uid(a.institutionId))}, null, 'SUBMITTED', 'INSTITUTION', 'Seeded', ${q(a.submittedAt)});`);
  if (a.status !== 'SUBMITTED') out.push(`insert into public.status_history(application_id, institution_id, from_status, to_status, actor_role, note, at) values (${q(uid(a.id))}, ${q(uid(a.institutionId))}, 'SUBMITTED', ${q(a.status)}, 'REVIEWER', 'Seeded', ${q(a.lastUpdatedAt)});`);
  for (const d of a.documents) {
    const mime = /\.png$/i.test(d.fileName) ? 'image/png' : /\.jpe?g$/i.test(d.fileName) ? 'image/jpeg' : 'application/pdf';
    out.push(`insert into public.application_documents(id, application_id, institution_id, doc_type, file_name, file_size_bytes, mime_type, file_hash, page_count, valid_till, version, status, extracted_fields, forensics, ai_analysis, uploaded_at)
values (${q(uid(d.id))}, ${q(uid(a.id))}, ${q(uid(a.institutionId))}, ${q(d.docType)}, ${q(d.fileName)}, ${d.fileSizeKb * 1024}, ${q(mime)}, ${q(d.fileHash)}, ${d.pageCount}, ${q(d.validTill)}, ${d.version}, ${q(d.status)}, ${j(d.extractedFields)}, ${j(d.forensics)}, ${j(d.geminiAnalysis)}, ${q(d.uploadedAt)}) on conflict (id) do nothing;`);
  }
  for (const f of a.findings) {
    out.push(`insert into public.findings(id, application_id, rule_code, rule_name, severity, description, handbook_clause, evidence_snippet, doc_type, rule_version)
values (${q(uid(f.id))}, ${q(uid(a.id))}, ${q(f.ruleCode)}, ${q(f.ruleName)}, ${q(f.severity)}, ${q(f.description)}, ${q(f.handbookClause)}, ${q(f.evidenceSnippet)}, ${q(f.docType)}, 'v2026.1') on conflict (id) do nothing;`);
  }
  const r = a.scrutinyRecommendation;
  if (r) {
    const pts = `array[${r.deficiencyPoints.map(q).join(',')}]::text[]`;
    out.push(`insert into public.scrutiny(application_id, institution_id, status, reviewer_name, rationale, deficiency_points, official_notice_number, updated_at)
values (${q(uid(a.id))}, ${q(uid(a.institutionId))}, ${q(r.status)}, ${q(r.reviewerName)}, ${q(r.rationale)}, ${r.deficiencyPoints.length ? pts : "'{}'"}, ${q(r.officialNoticeNumber)}, ${q(r.timestamp)}) on conflict (application_id) do nothing;`);
  }
}

for (const n of NOTIFS) {
  const link = n.link ? { route: n.link.route, id: uid(n.link.id) } : null;
  out.push(`insert into public.notifications(id, institution_id, title, message, type, link, is_read, created_at)
values (${q(uid(n.id))}, ${q(uid(n.institutionId))}, ${q(n.title)}, ${q(n.message)}, ${q(n.type)}, ${j(link)}, ${n.isRead}, ${q(n.timestamp)}) on conflict (id) do nothing;`);
}

for (const i of INSTITUTIONS) out.push(`select public._audit(${q(uid(i.id))}, null, 'Seed loader', 'SYSTEM', 'DEMO_DATA_LOADED', 'INSTITUTION', ${q(i.pid)}, 'Demo dataset loaded from the web prototype.');`);
out.push('commit;', '');

fs.writeFileSync(path.join(root, 'supabase', 'seed.sql'), out.join('\n'));
console.log('wrote supabase/seed.sql', out.length, 'statements');
