// Snapshots the project's source into supabase/functions/evaluator-guide/corpus.ts so the Evaluator Guide agent
// can search and read the real implementation. Re-run after changing the code:  node scripts/build-guide-corpus.mjs
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const rel = p => path.relative(root, p).split(path.sep).join('/');
const walk = (dir, ok) => fs.readdirSync(dir, { withFileTypes: true }).flatMap(e => {
  const p = path.join(dir, e.name);
  return e.isDirectory() ? walk(p, ok) : ok(p) ? [p] : [];
});

const files = [
  'README.md', 'web-portal/README.md', 'index.html', 'app.js', 'backend.js', 'config.js', 'sw.js', 'vercel.json',
  'web-portal/index.html', 'web-portal/vercel.json', '.github/workflows/supabase-deploy.yml', 'supabase/config.toml',
  'supabase/functions/analyze-document/index.ts', 'supabase/functions/analyze-document/extract.ts',
].map(f => path.join(root, f)).filter(f => fs.existsSync(f))
  .concat(walk(path.join(root, 'supabase', 'migrations'), p => p.endsWith('.sql')))
  .concat(walk(path.join(root, 'web-portal', 'src'), p => /\.(ts|tsx|css)$/.test(p) && !p.includes('mockData')));

const corpus = Object.fromEntries(files.map(f => [rel(f), fs.readFileSync(f, 'utf8').replace(/\r\n/g, '\n')]));
const out = path.join(root, 'supabase', 'functions', 'evaluator-guide', 'corpus.ts');
fs.writeFileSync(out, `// GENERATED by scripts/build-guide-corpus.mjs — do not edit by hand.\nexport const CORPUS: Record<string, string> = ${JSON.stringify(corpus, null, 0)};\n`);
const kb = Math.round(fs.statSync(out).size / 1024);
console.log(`evaluator-guide/corpus.ts: ${files.length} files, ${kb} KB`);
